#!/usr/bin/env bash
# Writes an nginx include that makes nginx trust Cloudflare's CF-Connecting-IP header, but only from Cloudflare's
# own addresses. Without it every visitor looks like a Cloudflare address and rate limits hit everyone at once.
#
#   sudo ./update-cloudflare-ips.sh                 writes /etc/nginx/cloudflare-realip.conf, then reload nginx
#   ./update-cloudflare-ips.sh /tmp/test.conf       write somewhere else (for a dry run)
#
# Cloudflare changes the list rarely; run it again now and then (a monthly cron job is plenty).
set -euo pipefail
OUT=${1:-/etc/nginx/cloudflare-realip.conf}
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  echo "# Generated by update-cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit."
  for list in ips-v4 ips-v6; do
    body=$(curl -fsS --max-time 20 "https://www.cloudflare.com/$list")
    [ -n "$body" ] || { echo "empty answer for $list" >&2; exit 1; }
    while read -r net; do
      case $net in
        ""|\#*) continue ;;
        *[!0-9a-fA-F:./]*) echo "unexpected line in $list: $net" >&2; exit 1 ;;
      esac
      echo "set_real_ip_from $net;"
    done <<<"$body"
  done
  echo "real_ip_header CF-Connecting-IP;"
} >"$tmp"

grep -q '^set_real_ip_from' "$tmp" || { echo "no networks found; keeping the old file" >&2; exit 1; }
install -m 0644 "$tmp" "$OUT"
echo "wrote $OUT ($(grep -c '^set_real_ip_from' "$OUT") networks). Now: nginx -t && systemctl reload nginx"
